"""Generate docs/re/structs-generated.md from re/structs/*.tsv and re/names/*.tsv (data rows).
Usage: python3 tools/structs_doc.py"""
import glob, collections, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
fields = collections.defaultdict(lambda: collections.defaultdict(list))
sizes = {}
for f in sorted(glob.glob(f'{ROOT}/re/structs/*.tsv')):
    src = os.path.basename(f)[:-4]
    for l in open(f):
        p = l.rstrip('\n').split('\t')
        if len(p) < 3 or p[0] in ('struct',) or l.startswith('#'): continue
        if p[1] == 'size': sizes[p[0]] = p[2]; continue
        fields[p[0]][int(p[1], 16) if p[1].startswith('0x') else int(p[1])].append((p[3] if len(p) > 3 else '?', p[2], src))
out = ['# Memory structures (generated)', '', 'Generated by `tools/structs_doc.py` from `re/structs/*.tsv`; do not edit. '
       'Several names at one offset = different subsystems named it (union by building type, or a conflict to resolve).', '']
for s in sorted(fields):
    out += [f'## {s} (size {sizes.get(s, "?")})', '', '| Off | Type | Name(s) | Source |', '|---|---|---|---|']
    for off in sorted(fields[s]):
        v = fields[s][off]
        names = ' / '.join(dict.fromkeys(x[0] for x in v))
        out.append(f'| +0x{off:02X} | {v[0][1]} | {names} | {", ".join(dict.fromkeys(x[2] for x in v))} |')
    out.append('')
glob_rows = []
# the fetched upstream names (tools/upstream_names.py) + ours, in file-name order like ApplyNames
for f in sorted(glob.glob(f'{ROOT}/re/names/*.tsv') + glob.glob(f'{ROOT}/re/names/.upstream/*.tsv'), key=os.path.basename):
    for l in open(f):
        p = l.rstrip('\n').split('\t')
        if len(p) > 2 and p[2] == 'data': glob_rows.append((p[0].lower().replace('0x', '').zfill(8), p[1], p[3] if len(p) > 3 else '', os.path.basename(f)[:-4]))
seen = {}
for a, n, t, src in glob_rows: seen[a] = (n, t, src)   # last file wins, like ApplyNames
out += ['## Globals', '', '| Address | Name | Type | Source |', '|---|---|---|---|']
out += [f'| `0x{a.upper()}` | {n} | {t} | {src} |' for a, (n, t, src) in sorted(seen.items())]
open(f'{ROOT}/docs/re/structs-generated.md', 'w').write('\n'.join(out) + '\n')
print(len(fields), 'structs,', sum(len(v) for v in fields.values()), 'offsets,', len(seen), 'globals')
