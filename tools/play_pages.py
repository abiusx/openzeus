"""Build data/play/pages.json: strings and exe tables of the control-panel pages' info boxes (docs/play/pages.md).

    re/venv/bin/python tools/play_pages.py      (needs pefile; reads Zeus.exe and extracted/text/zeus_text.json)

The layout of each page (positions, fonts, branches) is code in the exe (page functions listed in
docs/play/pages.md) and is written by hand in viewer/play/pages.js; this file only carries the data those
functions read: whole text groups they draw from and the level tables of the tax/wage arrows.
"""
import json
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from play_ui import rd  # noqa: E402  (Zeus.exe reader)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEXT = os.path.join(ROOT, "extracted", "text", "zeus_text.json")
OUT = os.path.join(ROOT, "data", "play", "pages.json")

# text groups drawn by the page functions (0x00518B20 .. 0x005B6F00); see docs/play/pages.md per page
GROUPS = [8, 18, 23, 50, 51, 133, 55, 56, 57, 58, 59, 60, 61, 62, 63, 64, 130, 131, 157, 190, 285, 286]


def ints(va, n):
    return list(struct.unpack("<%di" % n, rd(va, 4 * n)))


def main(extra=()):
    T = json.load(open(TEXT))
    out = {
        "_doc": "Generated by tools/play_pages.py (docs/play/pages.md): text groups of the page info boxes and the "
                "exe's level tables. Layout: viewer/play/pages.js.",
        "tax_levels": {"values": ints(0x00641F50, 7), "names_group": 286, "ev": "0x00641F50, arrows 0x005698B0/0x00569920"},
        "wage_levels": {"values": ints(0x00641F38, 6), "names_group": 285, "ev": "0x00641F38, arrows 0x005696D0/0x00569740"},
        "strings": {str(g): T[str(g)] for g in sorted(set(GROUPS) | set(extra)) if str(g) in T},
    }
    with open(OUT, "w") as fh:
        json.dump(out, fh, indent=1, ensure_ascii=False)
    print("wrote", OUT, len(out["strings"]), "groups")


if __name__ == "__main__":
    main([int(a) for a in sys.argv[1:]])
